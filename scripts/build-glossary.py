#!/usr/bin/env python3
"""Generate the glossary page HTML (static, works without JS), TS data, and a Markdown export
from src/lib/glossary.json. Run: python3 scripts/build-glossary.py [markdown_out]"""
import json, sys, html
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
D = json.loads((ROOT/'src/lib/glossary.json').read_text())
SECTIONS = ["Submitting", "Responses", "Rights & money", "Contests & fees", "Formats & genres"]
LINKS = {
  "tracker": ("Free printable: Submission Tracker", "/resources/#submission-tracker"),
  "cover": ("Free printable: Cover Letter Template", "/resources/#cover-letter-template"),
  "checklist": ("Free printable: Before You Hit Submit", "/resources/#before-you-hit-submit"),
  "desk": ("Covered in depth in The Submission Desk", "https://payhip.com/b/w5ih1"),
}
BY = {t['slug']: t for t in D}
URL = "https://amongtheletters.com/resources/glossary/"
e = html.escape

(ROOT/'src/lib/glossary-data.ts').write_text(
  "// Generated by scripts/build-glossary.py from glossary.json. Do not edit by hand.\n"
  "export type GlossaryTerm = { slug: string; term: string; section: string; definition: string; forYou: string; related: string[]; link?: string };\n"
  f"export const GLOSSARY_SECTIONS = {json.dumps(SECTIONS)} as const;\n"
  f"export const GLOSSARY_LINKS: Record<string, {{ label: string; href: string }}> = {json.dumps({k: {'label': v[0], 'href': v[1]} for k, v in LINKS.items()}, indent=2)};\n"
  f"export const GLOSSARY: GlossaryTerm[] = {json.dumps(D, indent=1, ensure_ascii=False)};\n")

# static HTML body
body = []
for sec in SECTIONS:
    body.append(f'<section><h2>{e(sec)}</h2><dl>')
    for t in sorted([t for t in D if t['section'] == sec], key=lambda t: t['term'].lower()):
        rel = ', '.join(f'<a href="#{r}">{e(BY[r]["term"])}</a>' for r in t['related'])
        link = ''
        if t.get('link'):
            l, h = LINKS[t['link']]; link = f' <a href="{h}">{e(l)}</a>.'
        body.append(f'<div id="{t["slug"]}"><dt><a href="#{t["slug"]}">{e(t["term"])}</a></dt><dd><p>{e(t["definition"])}</p>'
                    f'<p><strong>What this means for you:</strong> {e(t["forYou"])}{link}</p><p>Related: {rel}</p></dd></div>')
    body.append('</dl></section>')
ld = {"@context": "https://schema.org", "@graph": [
  {"@type": "Organization", "@id": "https://amongtheletters.com/#organization", "name": "Among The Letters", "url": "https://amongtheletters.com/"},
  {"@type": "DefinedTermSet", "@id": URL + "#termset", "name": "A Plain-Language Glossary for Writers", "url": URL, "inLanguage": "en-CA",
   "publisher": {"@id": "https://amongtheletters.com/#organization"},
   "hasDefinedTerm": [{"@type": "DefinedTerm", "@id": URL + "#" + t['slug'], "name": t['term'], "description": t['definition'],
                        "url": URL + "#" + t['slug'], "inDefinedTermSet": URL + "#termset", "termCode": t['slug']} for t in D]},
  {"@type": "BreadcrumbList", "itemListElement": [
    {"@type": "ListItem", "position": 1, "name": "Home", "item": "https://amongtheletters.com/"},
    {"@type": "ListItem", "position": 2, "name": "Free Resources", "item": "https://amongtheletters.com/resources/"},
    {"@type": "ListItem", "position": 3, "name": "Glossary", "item": URL}]}]}
desc = f"A plain-language glossary of {len(D)} terms writers meet when submitting work: simultaneous submissions, reading periods, rejections, FNASR and other rights, contest fees, flash fiction, chapbooks, and more."
page = f'''<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="description" content="{e(desc)}" />
    <meta name="author" content="Among The Letters" />
    <meta name="theme-color" content="#f3eee6" />
    <link rel="canonical" href="{URL}" />
    <link rel="icon" type="image/svg+xml" href="../../favicon.svg" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Among The Letters" />
    <meta property="og:title" content="A Plain-Language Glossary for Writers | Among The Letters" />
    <meta property="og:description" content="{e(desc)}" />
    <meta property="og:url" content="{URL}" />
    <meta property="og:image" content="https://amongtheletters.com/images/resources/glossary-og.jpg" />
    <meta name="twitter:image:alt" content="A Plain-Language Glossary for Writers, from the Among The Letters Free Resources library" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="A Plain-Language Glossary for Writers, from the Among The Letters Free Resources library" />
    <meta property="og:locale" content="en_CA" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="A Plain-Language Glossary for Writers | Among The Letters" />
    <meta name="twitter:description" content="{e(desc)}" />
    <meta name="twitter:image" content="https://amongtheletters.com/images/resources/glossary-og.jpg" />
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,400;0,9..144,500;0,9..144,600;0,9..144,700;1,9..144,400;1,9..144,500;1,9..144,600&family=Instrument+Sans:ital,wght@0,400;0,500;0,600;1,400&display=swap" rel="stylesheet" />
    <script type="application/ld+json">{json.dumps(ld, ensure_ascii=False)}</script>
    <title>A Plain-Language Glossary for Writers | Among The Letters</title>
  </head>
  <body>
    <div id="root">
      <header>
        <p><a href="/">Among The Letters</a> / <a href="/resources/">Free Resources</a></p>
        <h1>A Plain-Language Glossary for Writers</h1>
        <p>{len(D)} terms you will meet when sending your work out, explained simply.</p>
      </header>
      <main>
        {''.join(body)}
      </main>
    </div>
    <script type="module" src="/src/glossary-main.tsx"></script>
  </body>
</html>
'''
(ROOT/'resources/glossary/index.html').write_text(page)

if len(sys.argv) > 1:
    md = [f"# A Plain-Language Glossary for Writers\n\nAmong The Letters · Free Resources · {len(D)} terms\n"]
    for sec in SECTIONS:
        items = sorted([t for t in D if t['section'] == sec], key=lambda t: t['term'].lower())
        md.append(f"\n## {sec} ({len(items)})\n")
        for t in items:
            rel = ', '.join(BY[r]['term'] for r in t['related'])
            link = f" [{LINKS[t['link']][0]}: {LINKS[t['link']][1]}]" if t.get('link') else ''
            md.append(f"\n### {t['term']}  (#{t['slug']})\n\n{t['definition']}\n\n**What this means for you:** {t['forYou']}{link}\n\n*Related:* {rel}\n")
    Path(sys.argv[1]).write_text(''.join(md))
print(len(D), 'terms')
